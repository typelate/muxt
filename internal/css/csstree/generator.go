package csstree

import (
	"strings"

	"github.com/typelate/muxt/internal/css/csstree/tokenizer"
)

// GenerateHandlers are the generator's output steps (upstream handlers).
// Each function except TokenBefore receives the handlers in use as h
// (upstream this), so a decorated handler calls the decorated others.
type GenerateHandlers struct {
	// Node generates node, or fails for an unknown node type.
	Node func(h *GenerateHandlers, node Node)
	// TokenBefore decides on whitespace before a token (see
	// GenerateOptions.Mode).
	TokenBefore TokenBeforeFunc
	// Token emits a token, preceded by whitespace when TokenBefore asks
	// for it unless suppressAutoWhiteSpace is set.
	Token func(h *GenerateHandlers, tokenType tokenizer.TokenType, value string, suppressAutoWhiteSpace bool)
	// Emit appends value to the output; autoGenerated marks whitespace
	// the generator added.
	Emit func(h *GenerateHandlers, value string, tokenType tokenizer.TokenType, autoGenerated bool)
	// Result returns the output.
	Result func(h *GenerateHandlers) string
}

// GenerateOptions configures Generate. The zero value means upstream's
// defaults.
type GenerateOptions struct {
	// Mode selects how whitespace between tokens is decided: "safe" (the
	// default, also for "") or "spec". Other values are ignored.
	Mode string
	// Decorator, when set, receives the default handlers and returns the
	// handlers to use.
	Decorator func(handlers GenerateHandlers) GenerateHandlers
	// SourceMap, when set, receives a source map of the generated CSS
	// (upstream sourceMap: true, which makes generate return { css, map }).
	// Pass a new SourceMapGenerator: nodes need locations (ParseOptions
	// Positions), and only Atrule, Selector and Declaration nodes are
	// mapped.
	SourceMap *SourceMapGenerator
}

// UnknownNodeTypeError is returned by Generate for a node whose type has no
// generate function.
type UnknownNodeTypeError struct {
	Type string
}

func (e *UnknownNodeTypeError) Error() string {
	return "Unknown node type: " + e.Type
}

// Generator is the API a node generate function uses (upstream publicApi,
// the `this` of generate functions).
type Generator struct {
	handlers *GenerateHandlers
}

// Node generates node.
func (g *Generator) Node(node Node) {
	g.handlers.Node(g.handlers, node)
}

// Children generates the nodes of children, calling delimiter (when not
// nil) with the previous node between two nodes (upstream
// children(node, delimiter) takes the node and reads node.children).
func (g *Generator) Children(children *List[Node], delimiter func(prev Node)) {
	if delimiter != nil {
		var prev Node

		children.ForEach(func(node Node, _ *ListItem[Node], _ *List[Node]) {
			if prev != nil {
				delimiter(prev)
			}

			g.Node(node)
			prev = node
		})

		return
	}

	children.ForEach(func(node Node, _ *ListItem[Node], _ *List[Node]) {
		g.Node(node)
	})
}

// Token emits a token of tokenType with text value.
func (g *Generator) Token(tokenType tokenizer.TokenType, value string) {
	g.handlers.Token(g.handlers, tokenType, value, false)
}

// Tokenize splits raw into tokens and emits them.
func (g *Generator) Tokenize(raw string) {
	tokenizer.Tokenize(raw, func(tokenType tokenizer.TokenType, start, end int) {
		g.handlers.Token(
			g.handlers,
			tokenType,
			raw[start:end],
			start != 0, // suppress auto whitespace for internal value tokens
		)
	})
}

// generateFailure carries an UnknownNodeTypeError from the node handler up
// to the generate function.
type generateFailure struct {
	err error
}

// CreateGenerator returns a generate function for the node types of
// config (upstream createGenerator).
func CreateGenerator(config *Config) func(node Node, options GenerateOptions) (string, error) {
	types := make(map[string]GenerateFunc)

	if config != nil {
		for name, item := range config.Node {
			if item.Generate != nil {
				types[name] = item.Generate
			}
		}
	}

	return func(node Node, options GenerateOptions) (result string, err error) {
		var buffer strings.Builder
		prevCode := 0
		// a \ delim was emitted: \ and a newline is not an escape, so a
		// newline goes before the next text unless that text starts with one
		newlineDue := false
		var publicAPI *Generator
		handlers := GenerateHandlers{
			Node: func(_ *GenerateHandlers, node Node) {
				if node == nil {
					// upstream: node.type is undefined
					panic(generateFailure{&UnknownNodeTypeError{Type: "undefined"}})
				}
				if fn, ok := types[node.Type()]; ok {
					fn(publicAPI, node)
				} else {
					panic(generateFailure{&UnknownNodeTypeError{Type: node.Type()}})
				}
			},
			TokenBefore: safeTokenBefore(),
			Token: func(h *GenerateHandlers, tokenType tokenizer.TokenType, value string, suppressAutoWhiteSpace bool) {
				prevCode = h.TokenBefore(prevCode, tokenType, value)
				space := !suppressAutoWhiteSpace && prevCode&1 != 0

				if newlineDue && (space || value != "") {
					newlineDue = false
					if space || !startsWithNewline(value) {
						h.Emit(h, "\n", tokenizer.WhiteSpace, true)
					}
				}

				if space {
					h.Emit(h, " ", tokenizer.WhiteSpace, true)
				}

				h.Emit(h, value, tokenType, false)

				// A lone \ must not escape the next char, and a string left open
				// (a bad-string, or a Raw value ending inside a string) must end at
				// a newline (CSS Syntax 4.3.5) instead of swallowing what follows.
				if tokenType == tokenizer.BadString ||
					tokenType == tokenizer.String && !isClosedString(value) ||
					tokenType == tokenizer.Delim && tokenizer.CharCodeAt(value, 0) == reverseSolidus {
					newlineDue = true
				}
			},
			Emit: func(_ *GenerateHandlers, value string, _ tokenizer.TokenType, _ bool) {
				buffer.WriteString(value)
			},
			Result: func(*GenerateHandlers) string {
				return buffer.String()
			},
		}

		if options.Decorator != nil {
			handlers = options.Decorator(handlers)
		}

		if options.SourceMap != nil {
			handlers = generateSourceMap(handlers, options.SourceMap)
		}

		switch options.Mode {
		case "safe":
			handlers.TokenBefore = safeTokenBefore()
		case "spec":
			handlers.TokenBefore = specTokenBefore()
		}

		publicAPI = &Generator{handlers: &handlers}

		defer func() {
			if r := recover(); r != nil {
				if failure, ok := r.(generateFailure); ok {
					result, err = "", failure.err
					return
				}
				// upstream: whatever a generate function throws reaches the caller
				result, err = "", recoveredError(r)
			}
		}()

		handlers.Node(&handlers, node)

		if newlineDue {
			handlers.Emit(&handlers, "\n", tokenizer.WhiteSpace, true)
		}

		return handlers.Result(&handlers), nil
	}
}

// Generate turns an AST into CSS text with the default syntax (upstream
// generate).
func Generate(node Node, options GenerateOptions) (string, error) {
	return defaultParseSyntax().Generate(node, options)
}

// startsWithNewline reports whether text starts with a newline (LF, CR or
// FF; https://drafts.csswg.org/css-syntax-3/#newline).
func startsWithNewline(text string) bool {
	return text != "" && (text[0] == '\n' || text[0] == '\r' || text[0] == '\f')
}

// isClosedString reports whether a string token's text ends with the quote
// it starts with, unescaped. A string token at the end of its input may be
// left open (CSS Syntax 4.3.5: EOF ends the token without a closing quote).
func isClosedString(value string) bool {
	if len(value) < 2 || value[len(value)-1] != value[0] {
		return false
	}

	backslashes := 0
	for i := len(value) - 2; i > 0 && value[i] == '\\'; i-- {
		backslashes++
	}

	return backslashes%2 == 0
}
