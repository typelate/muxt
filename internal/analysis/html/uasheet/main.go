// Command uasheet extracts the user-agent style sheet from the Rendering
// section of the HTML Standard and writes the parts the whitespace
// classifier needs (display and white-space declarations).
//
// Usage:
//
//	uasheet -i rendering.html -o ua.css -date 2026-10-29
package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"slices"
	"strconv"
	"strings"

	"golang.org/x/net/html"

	"github.com/typelate/muxt/internal/css/csstree"
)

const (
	specURL = "https://html.spec.whatwg.org/multipage/rendering.html"
	xhtmlNS = `"http://www.w3.org/1999/xhtml"`
)

// fetched is the date the spec was downloaded, set by the -date flag.
var fetched string

// keptProperties are the declarations that decide how whitespace in an
// element's content is rendered.
var keptProperties = []string{"display", "display-outside", "white-space", "white-space-collapse", "text-wrap-mode"}

const headingList = "h1, h2, h3, h4, h5, h6"

func main() {
	var in, out string
	flag.StringVar(&in, "i", "", "path to the downloaded rendering.html")
	flag.StringVar(&out, "o", "", "path to write ua.css")
	flag.StringVar(&fetched, "date", "", "date the spec was fetched (YYYY-MM-DD)")
	flag.Parse()
	if in == "" || out == "" || fetched == "" {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(in, out); err != nil {
		log.Fatal(err)
	}
}

func run(in, out string) (err error) {
	src, err := os.Open(in)
	if err != nil {
		return err
	}
	defer func() { _ = src.Close() }()
	dst, err := os.Create(out)
	if err != nil {
		return err
	}
	defer func() { err = errors.Join(err, dst.Close()) }()
	return generate(bufio.NewReader(src), dst)
}

// generate reads the Rendering section from r and writes the filtered
// style sheet to w.
func generate(r io.Reader, w io.Writer) error {
	doc, err := html.Parse(r)
	if err != nil {
		return fmt.Errorf("parsing rendering section: %w", err)
	}
	blocks := cssBlocks(doc)
	var b strings.Builder
	fmt.Fprintf(&b, "/* Generated by uasheet from %s (fetched %s). Derived from the HTML Standard, © WHATWG, CC BY 4.0. */\n", specURL, fetched)
	for _, block := range blocks {
		out, err := filterBlock(block)
		if err != nil {
			return err
		}
		b.WriteString(out)
	}
	_, err = io.WriteString(w, b.String())
	return err
}

// cssBlocks returns the text of every pre > code.css block in sections
// 15.3 to 15.5 that starts with the XHTML @namespace rule and does not
// follow a paragraph about quirks mode.
func cssBlocks(doc *html.Node) []string {
	var (
		blocks  []string
		section string
		lastP   string
	)
	var walk func(n *html.Node)
	walk = func(n *html.Node) {
		if n.Type == html.ElementNode {
			switch n.Data {
			case "h3", "h4":
				section = headingNumber(n)
				lastP = ""
			case "p":
				lastP = text(n)
			case "code":
				if n.Parent != nil && n.Parent.Data == "pre" && hasClass(n, "css") && inRenderedSections(section) {
					src := text(n)
					if strings.HasPrefix(strings.TrimSpace(src), "@namespace") && !strings.Contains(lastP, "In quirks mode") {
						blocks = append(blocks, src)
					}
				}
				return
			}
		}
		for c := n.FirstChild; c != nil; c = c.NextSibling {
			walk(c)
		}
	}
	walk(doc)
	return blocks
}

func headingNumber(h *html.Node) string {
	for c := h.FirstChild; c != nil; c = c.NextSibling {
		if c.Type == html.ElementNode && hasClass(c, "secno") {
			return strings.TrimSpace(text(c))
		}
	}
	return ""
}

// inRenderedSections reports whether number is 15.3, 15.4, or 15.5 or one
// of their subsections.
func inRenderedSections(number string) bool {
	parts := strings.Split(number, ".")
	if len(parts) < 2 || parts[0] != "15" {
		return false
	}
	minor, err := strconv.Atoi(parts[1])
	return err == nil && minor >= 3 && minor <= 5
}

func hasClass(n *html.Node, class string) bool {
	for _, a := range n.Attr {
		if a.Key == "class" && slices.Contains(strings.Fields(a.Val), class) {
			return true
		}
	}
	return false
}

func text(n *html.Node) string {
	var b strings.Builder
	var walk func(n *html.Node)
	walk = func(n *html.Node) {
		if n.Type == html.TextNode {
			b.WriteString(n.Data)
		}
		for c := n.FirstChild; c != nil; c = c.NextSibling {
			walk(c)
		}
	}
	walk(n)
	return b.String()
}

// filterBlock parses one CSS block and returns its kept rules, each
// followed by a blank line separator, with a leading blank line.
func filterBlock(src string) (string, error) {
	ast, err := csstree.Parse(src, csstree.ParseOptions{})
	if err != nil {
		return "", fmt.Errorf("parsing css block: %w", err)
	}
	sheet, ok := ast.(*csstree.StyleSheet)
	if !ok {
		return "", fmt.Errorf("css block parsed as %s, want StyleSheet", ast.Type())
	}
	var b strings.Builder
	if err := writeNodes(&b, sheet.Children, ""); err != nil {
		return "", err
	}
	return b.String(), nil
}

func writeNodes(b *strings.Builder, children *csstree.List[csstree.Node], indent string) error {
	for n := range children.All() {
		switch n := n.(type) {
		case *csstree.Rule:
			if err := writeRule(b, n, indent); err != nil {
				return err
			}
		case *csstree.Atrule:
			if n.Name == "namespace" || n.Block == nil {
				continue
			}
			var inner strings.Builder
			if err := writeNodes(&inner, n.Block.Children, indent+"  "); err != nil {
				return err
			}
			if inner.Len() == 0 {
				continue
			}
			prelude, err := generateNode(n.Prelude)
			if err != nil {
				return err
			}
			fmt.Fprintf(b, "\n%s@%s %s {%s%s}\n", indent, n.Name, prelude, strings.TrimRight(inner.String(), "\n")+"\n", indent)
		}
	}
	return nil
}

func writeRule(b *strings.Builder, rule *csstree.Rule, indent string) error {
	var decls []string
	for n := range rule.Block.Children.All() {
		d, ok := n.(*csstree.Declaration)
		if !ok || !slices.Contains(keptProperties, d.Property) {
			continue
		}
		value, err := generateNode(d.Value)
		if err != nil {
			return err
		}
		important := ""
		if d.Important != "" {
			important = " !important"
		}
		decls = append(decls, fmt.Sprintf("%s  %s: %s%s;\n", indent, d.Property, value, important))
	}
	if len(decls) == 0 {
		return nil
	}
	selectors, err := selectorList(rule.Prelude)
	if err != nil {
		return err
	}
	if len(selectors) == 0 {
		return nil
	}
	fmt.Fprintf(b, "\n%s%s {\n%s%s}\n", indent, strings.Join(selectors, ", "), strings.Join(decls, ""), indent)
	return nil
}

// selectorList returns the rule's selectors with :heading expanded to the
// six heading elements.
func selectorList(prelude csstree.Node) ([]string, error) {
	list, ok := prelude.(*csstree.SelectorList)
	if !ok {
		return nil, fmt.Errorf("rule prelude is %s, want SelectorList", prelude.Type())
	}
	var selectors []string
	for n := range list.Children.All() {
		s, err := generateNode(n)
		if err != nil {
			return nil, err
		}
		s, keep := staticSelector(s)
		if !keep {
			continue
		}
		switch {
		case s == ":heading":
			s = headingList
		case strings.Contains(s, ":heading"):
			s = strings.ReplaceAll(s, ":heading", ":is("+headingList+")")
		}
		selectors = append(selectors, s)
	}
	return selectors, nil
}

// staticSelector rewrites s for a document that is not running: a popover
// is never open, so :not(:popover-open) always matches and is removed.
// Selectors that can never match an element (a positive :popover-open) or
// that style a pseudo-element rather than the element itself are dropped.
func staticSelector(s string) (string, bool) {
	s = strings.ReplaceAll(s, ":not(:popover-open)", "")
	if strings.Contains(s, ":popover-open") || strings.Contains(s, "::") {
		return "", false
	}
	return s, true
}

func generateNode(n csstree.Node) (string, error) {
	s, err := csstree.Generate(n, csstree.GenerateOptions{})
	if err != nil {
		return "", fmt.Errorf("generating css: %w", err)
	}
	return strings.TrimSpace(s), nil
}
